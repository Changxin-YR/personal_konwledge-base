function patchText(dataDir, disabled = false) {
  const normalized = dataDir.replace(/\\/g, '/')
  return `# FND-002 test profile overlay (generated by scripts/fnd002/run-all.mjs).\n`
    + `- id: knowledgeos-host\n`
    + `  config:\n`
    + `    dataDir: "${normalized}"\n`
    + (disabled ? '  disabled: true\n' : '')
}

async function setPatch(dataDir, disabled = false) {
  writeFileSync(PATCH_PATH, patchText(dataDir, disabled), 'utf8')
}

async function boot(dataDir, suffix = 'host', disabled = false) {
  if (current !== null) await stopHost(current)
  await setPatch(dataDir, disabled)
  current = await startHost({ port: PORT, profile: PROFILE, logFile: join(OUT, `${suffix}.log`) })
  const { cookie } = await entryCookie(current.entryUrl)
  return cookie
}

async function shutdown() {
  if (current !== null) await stopHost(current)
  current = null
}

async function waitFor(predicate, timeoutMs, label) {
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    if (await predicate()) return true
    await sleep(250)
  }
  throw new Error(`timed out waiting for ${label}`)
}

function sqlite(dbPath, sql, params = []) {
  const db = new DatabaseSync(dbPath, { readOnly: true })
  try { return db.prepare(sql).all(...params) } finally { db.close() }
}

function rowCount(dbPath, where = '', params = []) {
  const rows = sqlite(dbPath, `SELECT count(*) AS count FROM storage_probe_records ${where}`, params)
  return Number(rows[0].count)
}

function dbPath(dataDir) {
  return join(dataDir, 'knowledgeos.sqlite')
}

async function createFixture(dataDir, kind) {
  rmSync(dataDir, { recursive: true, force: true })
  mkdirSync(dataDir, { recursive: true })
  const path = join(dataDir, 'knowledgeos.sqlite')
  const db = new DatabaseSync(path)
  try {
    if (kind === 'unknown-view') {
      db.exec('CREATE VIEW foreign_view AS SELECT 1 AS value')
      return path
    }
    if (kind === 'r1-foreign-table') {
      db.exec('CREATE TABLE sqliteX_foreign_private (id INTEGER PRIMARY KEY, secret TEXT NOT NULL)')
      db.prepare('INSERT INTO sqliteX_foreign_private (id, secret) VALUES (?, ?)').run(1, 't04-r1-sentinel')
      return path
    }
    db.exec(MIGRATION_V1_SQL)
    db.prepare('INSERT INTO schema_migrations (version, checksum, applied_at) VALUES (?, ?, ?)')
      .run(1, kind === 'bad-checksum' ? '0'.repeat(64) : MIGRATION_V1_CHECKSUM, new Date().toISOString())
    if (kind === 'unknown-schema') {
      db.exec('CREATE TABLE foreign_business (id TEXT PRIMARY KEY)')
      db.exec('PRAGMA application_id = 0')
      db.exec('PRAGMA user_version = 0')
    } else if (kind === 'wrong-app') {
      db.exec('PRAGMA application_id = 12345')
      db.exec('PRAGMA user_version = 1')
    } else if (kind === 'future') {
      db.exec(`PRAGMA application_id = ${0x4b4f5331}`)
      db.exec('PRAGMA user_version = 2')
    } else if (kind === 'bad-checksum') {
      db.exec(`PRAGMA application_id = ${0x4b4f5331}`)
      db.exec('PRAGMA user_version = 1')
    }
    db.prepare('INSERT INTO storage_probe_records (id, idempotency_key, request_digest, content, created_at) VALUES (?, ?, ?, ?, ?)')
      .run('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', 'c'.repeat(64), 'fixture', '2026-01-01T00:00:00.000Z')
  } finally {
    db.close()
  }
  return path
}

async function run(id, name, fn) {
  if (ONLY !== undefined && !ONLY.has(id)) return
  const started = new Date().toISOString()
  const detail = { id, name, status: 'FAIL', started, assertions: [], details: {}, evidence: [] }
  console.log(`\n=== ${id} ${name} ===`)
  try {
    const outcome = await fn(detail)
    detail.status = 'PASS'
    if (outcome !== undefined) detail.details = { ...detail.details, ...outcome }
    console.log(`PASS ${id}`)
  } catch (error) {
    detail.status = 'FAIL'
    detail.error = error instanceof Error ? error.stack ?? error.message : String(error)
    failures.push(`${id}: ${error instanceof Error ? error.message : String(error)}`)
    console.log(`FAIL ${id}: ${detail.error}`)
  } finally {
    detail.finished = new Date().toISOString()
    writeFileSync(join(OUT, `${id}.json`), `${JSON.stringify(detail, null, 2)}\n`, 'utf8')
    results.push({ id, name, status: detail.status, started: detail.started, finished: detail.finished, evidence: `${id}.json` })
    await shutdown()
  }
}

function expect(detail, expression, message, actual) {
  detail.assertions.push({ ok: Boolean(expression), message, actual })
  if (!expression) throw new Error(`${message}${actual === undefined ? '' : ` (${JSON.stringify(actual)})`}`)
}

